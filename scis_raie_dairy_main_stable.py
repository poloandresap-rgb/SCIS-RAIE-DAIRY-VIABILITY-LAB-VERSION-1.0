    def print_execution_summary(self) -> None:
        if not self.kpi_summary:
            self.compute_kpis()

        print("\n" + "=" * 72)
        print(self.metadata.software_name)
        print(f"Version: {self.metadata.version}")
        print(f"Solver used: {self.solver_name_used}")
        print("=" * 72)

        print("\nGLOBAL SUMMARY")
        for k, v in self.kpi_summary.items():
            print(f"  {k:20s}: {v:,.6f}")

        print("\nSCENARIO KPI TABLE")
        print(self.kpi_by_scenario.to_string(index=False))

        score = self.validation_score()
        if not np.isnan(score):
            print(f"\nValidation score (0-1): {score:.4f}")

    def print_calibration_guidance(self) -> None:
        if self.validation_table.empty:
            self.build_validation_report()
        if self.validation_table.empty:
            print("No validation data available.")
            return

        mean_gap = (
            self.validation_table.groupby("metric")["relative_gap"]
            .mean()
            .sort_values(ascending=False)
        )

        print("\nCALIBRATION GUIDANCE")
        print("-" * 72)
        for metric, gap in mean_gap.items():
            print(f"{metric:20s} mean relative gap = {gap:.4f}")


